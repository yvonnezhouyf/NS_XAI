#!/usr/bin/env python3
"""
Delta-Recovery evaluation for non-stationary explanations.

This script measures whether an explanation communicates the true temporal
change between the current snapshot and the reference snapshot. It is designed
to compare the full method against B4/A1 single-snapshot explanations:

  - targets are always built from full reference evidence, usually
    evaluation/faithfulness/evidence_240.json
  - explanations come from the method being evaluated, e.g. full ours or B4
  - an independent LLM reads only the explanation and predicts the communicated
    change direction/magnitude for each target component
  - deterministic scoring compares predictions to the hidden target deltas

Example, full method:

  python evaluation/delta_recovery/delta_recovery.py \
    --method-name ours \
    --explanations evaluation/faithfulness/evidence_240.json \
    --reference-evidence evaluation/faithfulness/evidence_240.json \
    --predictions-output evaluation/delta_recovery/ours_predictions_240.json \
    --graded-output evaluation/delta_recovery/ours_graded_240.json \
    --workers 4 --resume

Example, B4/A1:

  python evaluation/delta_recovery/delta_recovery.py \
    --method-name b4_single_snapshot \
    --explanations evaluation/baselines/b4_single_snapshot/evidence_240.json \
    --reference-evidence evaluation/faithfulness/evidence_240.json \
    --predictions-output evaluation/delta_recovery/b4_predictions_240.json \
    --graded-output evaluation/delta_recovery/b4_graded_240.json \
    --workers 4 --resume
"""

