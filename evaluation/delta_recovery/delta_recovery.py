DELTA_RECOVERY_PROMPT = """You are evaluating whether an explanation communicates temporal changes in a dispatch decision.

You will receive:
- a user query
- an explanation generated by a method
- a list of target components

The target list identifies which temporal changes should be recoverable. It does NOT include the ground-truth values. Your job is to read the explanation only and recover what temporal change the explanation communicates.

Rules:
- A current-only statement is not a temporal change. For example, "Vehicle 4 is at 91.8 minutes" does not recover a delta unless the explanation also gives an earlier/reference value or explicitly states how it changed.
- For delta targets, output direction:
  "+" if the component increased from the reference snapshot to the current snapshot,
  "-" if it decreased,
  "0" if it stayed effectively unchanged,
  null if the explanation does not communicate the direction.
- For delta targets, output magnitude when the explanation gives enough numbers or wording to estimate it. Magnitude is absolute and must use the target unit.
- For scalar targets, such as a recovery interval boundary, output scalar_value when the explanation gives the value.
- If the explanation says the method cannot determine a temporal change, mark the relevant component as "unknown_or_unrecoverable".
- Do not use outside knowledge. Do not infer from the target name alone. Use only the explanation text.
- Short evidence_text snippets are useful but optional; keep them brief.

Return exactly one JSON object:
{
  "components": [
    {
      "component_id": "...",
      "status": "recovered" | "not_mentioned" | "unknown_or_unrecoverable",
      "direction": "+" | "-" | "0" | null,
      "magnitude": number | null,
      "scalar_value": number | null,
      "evidence_text": "brief quote or null"
    }
  ]
}
"""


