def _read_json(path: str) -> Any:
    with open(path) as f:
        return json.load(f)


def _write_json_atomic(path: str, data: Any) -> None:
    os.makedirs(os.path.dirname(os.path.abspath(path)) or ".", exist_ok=True)
    tmp = path + ".tmp"
    with open(tmp, "w") as f:
        json.dump(data, f, indent=2, ensure_ascii=False)
    os.replace(tmp, path)


def _to_float(x: Any) -> Optional[float]:
    try:
        if x is None or isinstance(x, bool):
            return None
        return float(x)
    except (TypeError, ValueError):
        return None


def _sign(x: float, eps: float = 1e-9) -> str:
    if abs(x) <= eps:
        return "0"
    return "+" if x > 0 else "-"


def _rankdata(xs: List[float]) -> List[float]:
    order = sorted(range(len(xs)), key=lambda i: xs[i])
    ranks = [0.0] * len(xs)
    i = 0
    while i < len(order):
        j = i + 1
        while j < len(order) and xs[order[j]] == xs[order[i]]:
            j += 1
        avg = (i + 1 + j) / 2.0
        for k in range(i, j):
            ranks[order[k]] = avg
        i = j
    return ranks


def _pearson(xs: List[float], ys: List[float]) -> Optional[float]:
    if len(xs) < 2 or len(ys) < 2 or len(xs) != len(ys):
        return None
    mx = sum(xs) / len(xs)
    my = sum(ys) / len(ys)
    vx = sum((x - mx) ** 2 for x in xs)
    vy = sum((y - my) ** 2 for y in ys)
    if vx <= 0 or vy <= 0:
        return None
    cov = sum((x - mx) * (y - my) for x, y in zip(xs, ys))
    return cov / math.sqrt(vx * vy)


def _spearman(xs: List[float], ys: List[float]) -> Optional[float]:
    if len(xs) < 2 or len(ys) < 2 or len(xs) != len(ys):
        return None
    return _pearson(_rankdata(xs), _rankdata(ys))


def _vehicle_sort_key(item: Tuple[str, Any]) -> Tuple[int, str]:
    key, _ = item
    if isinstance(key, str) and re.fullmatch(r"V\d+", key):
        return (int(key[1:]), key)
    return (999, str(key))


def _vehicle_keys_in_current_side(line: str) -> Optional[List[str]]:
    current_side = line.split("|", 1)[0]
    keys: List[str] = []
    for m in re.finditer(r"\b(V\d+)\s*=", current_side):
        key = m.group(1)
        if key not in keys:
            keys.append(key)
    return keys or None


def _section_lines(text: str, header: str,
                   stop_headers: Sequence[str] = ()) -> List[str]:
    lines = (text or "").splitlines()
    try:
        start = next(i for i, line in enumerate(lines) if line.strip() == header)
    except StopIteration:
        return []
    out = []
    for line in lines[start + 1:]:
        stripped = line.strip()
        if stripped in stop_headers:
            break
        out.append(line)
    return out


def _extract_visible_pctl_specs(record: Dict[str, Any]
                                ) -> List[Tuple[str, Optional[List[str]]]]:
    evidence = record.get("evidence", {}).get("E_t", {}) or {}
    lines = _section_lines(
        record.get("llm_input") or "",
        PCTL_SECTION_HEADER,
        stop_headers=(DERIVED_SECTION_HEADER,),
    )
    specs: List[Tuple[str, Optional[List[str]]]] = []
    current_metric: Optional[str] = None
    for line in lines:
        m = re.match(r"^\s{2}(.+):\s*$", line)
        if m:
            metric = m.group(1).strip()
            current_metric = (
                metric if metric in evidence and not metric.startswith("DERIVED:")
                else None
            )
            continue
        if current_metric and "MDP_t (current model):" in line:
            specs.append((current_metric, _vehicle_keys_in_current_side(line)))
            current_metric = None
        elif current_metric and "Current model:" in line:
            specs.append((current_metric, _vehicle_keys_in_current_side(line)))
            current_metric = None

    if specs:
        return specs
    return [
        (f, None) for f in (record.get("pctl_formulas") or [])
        if f in evidence and not str(f).startswith("DERIVED:")
    ]


def _extract_visible_derived_specs(record: Dict[str, Any]
                                   ) -> List[Tuple[str, Optional[List[str]]]]:
    evidence = record.get("evidence", {}).get("E_t", {}) or {}
    lines = _section_lines(record.get("llm_input") or "", DERIVED_SECTION_HEADER)
    specs: List[Tuple[str, Optional[List[str]]]] = []
    for line in lines:
        m = re.match(r"^\s{4}([A-Z0-9_]+)(?:\s+\([^)]+\))?:", line)
        if not m:
            continue
        metric = f"DERIVED: {m.group(1)}"
        if metric in evidence:
            specs.append((metric, _vehicle_keys_in_current_side(line)))

    if specs:
        return specs
    return [
        (f, None) for f in (record.get("pctl_formulas") or [])
        if f in evidence and str(f).startswith("DERIVED:")
    ]


def _metric_label(metric: str) -> str:
    if metric.startswith("DERIVED: "):
        return metric.replace("DERIVED: ", "")
    return metric


def _metric_unit(metric: str, cur: float, prev: float) -> Tuple[str, float, float, float]:
    if metric.startswith("P=?"):
        return "percentage_points", cur * 100.0, prev * 100.0, (cur - prev) * 100.0
    if metric in {
        "DERIVED: ETA_PICKUP_BY_VEHICLE",
        "DERIVED: ETA_DROPOFF_BY_VEHICLE",
        "DERIVED: CLEAR_CURRENT_ROUTE_TIME_BY_VEHICLE",
        "DERIVED: DEADHEAD_TO_PICKUP_BY_VEHICLE",
        "DERIVED: DROPOFF_SLACK_BY_VEHICLE",
    }:
        return "minutes", cur, prev, cur - prev
    if "CONFIDENCE" in metric:
        return "percentage_points", cur * 100.0, prev * 100.0, (cur - prev) * 100.0
    return "raw_units", cur, prev, cur - prev


def _threshold_for(unit: str, metric: str, args: argparse.Namespace) -> float:
    if unit == "percentage_points":
        return args.min_prob_delta_pp
    if unit == "minutes":
        return args.min_minute_delta
    if "REQUESTS" in metric or "PENDING" in metric:
        return args.min_count_delta
    return args.min_raw_delta


def _iter_metric_items(value: Any, keys: Optional[List[str]]) -> List[Tuple[str, Any]]:
    if isinstance(value, dict):
        if keys:
            items = [(k, value.get(k)) for k in keys if k in value]
        else:
            items = [(k, v) for k, v in value.items() if re.fullmatch(r"V\d+", str(k))]
        return sorted(items, key=_vehicle_sort_key)
    return [("global", value)]


def _make_component_id(metric: str, subject: str, role: str = "delta") -> str:
    return f"{metric}::{subject}::{role}"


def _turning_interval_targets(record: Dict[str, Any]) -> List[Dict[str, Any]]:
    raw = (record.get("evidence", {}).get("E_t", {}) or {}).get(TURNING_INTERVAL)
    if not isinstance(raw, dict):
        return []
    interval = raw.get("display_interval")
    if not (isinstance(interval, list) and len(interval) >= 2):
        return []
    targets = []
    for role, idx, label in (
        ("display_start", 0, "start of the displayed recovery interval"),
        ("display_end", 1, "end of the displayed recovery interval"),
    ):
        val = _to_float(interval[idx])
        if val is None:
            continue
        targets.append({
            "component_id": _make_component_id(TURNING_INTERVAL, "global", role),
            "kind": "scalar",
            "metric": TURNING_INTERVAL,
            "metric_label": "TURNING_INTERVAL",
            "subject": "global",
            "unit": "request_index",
            "target_value": val,
            "tolerance": 0.5,
            "description": label,
        })
    return targets


def build_targets(record: Dict[str, Any], args: argparse.Namespace) -> List[Dict[str, Any]]:
    """Build hidden target components from full reference evidence."""
    evidence = record.get("evidence") or {}
    e_t = evidence.get("E_t") or {}
    e_prev = evidence.get("E_t_prev") or {}
    if not isinstance(e_t, dict) or not isinstance(e_prev, dict):
        return []

    targets: List[Dict[str, Any]] = []

    # Type-4 / recovery interval target. This is scalar, not a delta sign.
    if TURNING_INTERVAL in e_t:
        targets.extend(_turning_interval_targets(record))

    specs = _extract_visible_pctl_specs(record) + _extract_visible_derived_specs(record)
    for metric, keys in specs:
        if metric == TURNING_INTERVAL:
            continue
        if metric not in e_t or metric not in e_prev:
            continue
        cur_items = _iter_metric_items(e_t[metric], keys)
        prev_items = dict(_iter_metric_items(e_prev[metric], keys))
        for subject, cur_raw in cur_items:
            prev_raw = prev_items.get(subject)
            cur = _to_float(cur_raw)
            prev = _to_float(prev_raw)
            if cur is None or prev is None:
                continue
            unit, cur_u, prev_u, delta_u = _metric_unit(metric, cur, prev)
            threshold = _threshold_for(unit, metric, args)
            if abs(delta_u) < threshold and not args.include_zero_deltas:
                continue
            component_id = _make_component_id(metric, subject)
            targets.append({
                "component_id": component_id,
                "kind": "delta",
                "metric": metric,
                "metric_label": _metric_label(metric),
                "subject": subject,
                "unit": unit,
                "previous_value": round(prev_u, 6),
                "current_value": round(cur_u, 6),
                "delta_value": round(delta_u, 6),
                "abs_delta": round(abs(delta_u), 6),
                "sign": _sign(delta_u, eps=1e-9),
                "description": (
                    f"current minus reference change in {_metric_label(metric)}"
                    f" for {subject}"
                ),
            })

    scalar_targets = [t for t in targets if t["kind"] == "scalar"]
    delta_targets = [t for t in targets if t["kind"] == "delta"]
    delta_targets.sort(key=lambda t: abs(t.get("abs_delta", 0.0)), reverse=True)
    if args.max_delta_targets and len(delta_targets) > args.max_delta_targets:
        delta_targets = delta_targets[:args.max_delta_targets]
    return scalar_targets + delta_targets


def _public_targets_for_prompt(targets: List[Dict[str, Any]]) -> List[Dict[str, Any]]:
    public = []
    for t in targets:
        public.append({
            "component_id": t["component_id"],
            "kind": t["kind"],
            "metric_label": t["metric_label"],
            "subject": t["subject"],
            "unit": t["unit"],
            "description": t["description"],
        })
    return public


def _prompt_for_record(record: Dict[str, Any], targets: List[Dict[str, Any]]) -> str:
    payload = {
        "query_id": record.get("query_id"),
        "query": record.get("query_text"),
        "explanation": record.get("explanation") or "",
        "target_components": _public_targets_for_prompt(targets),
    }
    return json.dumps(payload, indent=2, ensure_ascii=False)


async def _call_llm(prompt: str, model: str, timeout_sec: float) -> Dict[str, Any]:
    from openai import AsyncOpenAI
    client = AsyncOpenAI()
    coro = client.chat.completions.create(
        model=model,
        messages=[
            {"role": "system", "content": DELTA_RECOVERY_PROMPT},
            {"role": "user", "content": prompt},
        ],
        response_format={"type": "json_object"},
        temperature=0.0,
    )
    if timeout_sec > 0:
        resp = await asyncio.wait_for(coro, timeout=timeout_sec)
    else:
        resp = await coro
    txt = resp.choices[0].message.content or "{}"
    return json.loads(txt)


async def _process_record(expl_record: Dict[str, Any], ref_record: Dict[str, Any],
                          args: argparse.Namespace) -> Dict[str, Any]:
    t0 = time.time()
    qid = expl_record.get("query_id")
    targets = build_targets(ref_record, args)
    out: Dict[str, Any] = {
        "query_id": qid,
        "type_k": ref_record.get("type_k", expl_record.get("type_k")),
        "scenario": ref_record.get("scenario", expl_record.get("scenario")),
        "query_text": ref_record.get("query_text", expl_record.get("query_text")),
        "method_name": args.method_name,
        "targets": targets,
        "target_count": len(targets),
        "status": "pending",
        "prediction": {"components": []},
    }

    if not targets:
        out["status"] = "no_targets"
        out["elapsed_sec"] = round(time.time() - t0, 2)
        return out
    if not expl_record.get("explanation"):
        out["status"] = "no_explanation"
        out["elapsed_sec"] = round(time.time() - t0, 2)
        return out
    if args.skip_llm:
        out["status"] = "skipped"
        out["elapsed_sec"] = round(time.time() - t0, 2)
        return out

    try:
        prompt = _prompt_for_record(expl_record, targets)
        raw = await _call_llm(prompt, args.model, args.timeout_sec)
        comps = raw.get("components", [])
        if not isinstance(comps, list):
            raise ValueError("LLM JSON field 'components' is not a list")
        out["prediction"] = {"components": comps}
        out["status"] = "ok"
    except Exception:
        out["status"] = "error"
        out["error"] = traceback.format_exc()
        out["prediction"] = {"components": []}

    out["elapsed_sec"] = round(time.time() - t0, 2)
    return out


async def _run_predictions(expl_records: List[Dict[str, Any]],
                           ref_by_id: Dict[str, Dict[str, Any]],
                           args: argparse.Namespace) -> List[Dict[str, Any]]:
    existing: Dict[str, Dict[str, Any]] = {}
    if args.resume and os.path.exists(args.predictions_output):
        try:
            data = _read_json(args.predictions_output)
            if isinstance(data, dict) and isinstance(data.get("records"), list):
                for rec in data["records"]:
                    if isinstance(rec, dict) and rec.get("query_id"):
                        existing[rec["query_id"]] = rec
            elif isinstance(data, list):
                for rec in data:
                    if isinstance(rec, dict) and rec.get("query_id"):
                        existing[rec["query_id"]] = rec
        except Exception as e:
            print(f"[warn] could not parse existing predictions: {e}; starting fresh")
            existing = {}

    to_run = []
    all_ids = [r.get("query_id") for r in expl_records if r.get("query_id")]
    for rec in expl_records:
        qid = rec.get("query_id")
        if not qid:
            continue
        if (
            args.resume
            and qid in existing
            and existing[qid].get("status") in COMPLETED_STATUSES
        ):
            continue
        ref = ref_by_id.get(qid)
        if ref is None:
            existing[qid] = {
                "query_id": qid,
                "status": "missing_reference",
                "targets": [],
                "prediction": {"components": []},
            }
            continue
        to_run.append((rec, ref))

    print(f"[resume] {len(existing)} existing; {len(to_run)} to run")
    semaphore = asyncio.Semaphore(max(1, args.workers))

    async def _bounded(pair):
        async with semaphore:
            return await _process_record(pair[0], pair[1], args)

    tasks = [asyncio.create_task(_bounded(p)) for p in to_run]
    for i, task in enumerate(asyncio.as_completed(tasks), 1):
        out = await task
        existing[out["query_id"]] = out
        mark = "OK " if out.get("status") == "ok" else "ERR" if out.get("status") == "error" else "..."
        print(
            f"[{i}/{len(tasks)}] {mark} {out['query_id']} "
            f"status={out.get('status')} targets={out.get('target_count', 0)}"
        )
        _write_predictions(args.predictions_output, args, existing, all_ids)

    _write_predictions(args.predictions_output, args, existing, all_ids)
    return [existing[qid] for qid in all_ids if qid in existing]


def _write_predictions(path: str, args: argparse.Namespace,
                       records_by_id: Dict[str, Dict[str, Any]],
                       order: Iterable[str]) -> None:
    prompt_sha = hashlib.sha256(DELTA_RECOVERY_PROMPT.encode("utf-8")).hexdigest()
    out = {
        "method_name": args.method_name,
        "created_at": datetime.now(timezone.utc).isoformat().replace("+00:00", "Z"),
        "model": args.model,
        "prompt_source": "embedded:DELTA_RECOVERY_PROMPT",
        "prompt_sha256": prompt_sha,
        "config": {
            "min_prob_delta_pp": args.min_prob_delta_pp,
            "min_minute_delta": args.min_minute_delta,
            "min_count_delta": args.min_count_delta,
            "min_raw_delta": args.min_raw_delta,
            "max_delta_targets": args.max_delta_targets,
            "include_zero_deltas": args.include_zero_deltas,
            "skip_llm": args.skip_llm,
        },
        "records": [records_by_id[qid] for qid in order if qid in records_by_id],
    }
    _write_json_atomic(path, out)


def _canonical_direction(x: Any) -> Optional[str]:
    if x in ("+", "-", "0"):
        return x
    if isinstance(x, str):
        low = x.strip().lower()
        if low in ("increase", "increased", "up", "higher", "positive", "+"):
            return "+"
        if low in ("decrease", "decreased", "down", "lower", "negative", "-"):
            return "-"
        if low in ("same", "unchanged", "zero", "0", "no change"):
            return "0"
    return None


def _pred_map(pred_record: Dict[str, Any]) -> Dict[str, Dict[str, Any]]:
    out = {}
    comps = (pred_record.get("prediction") or {}).get("components") or []
    if not isinstance(comps, list):
        return out
    for c in comps:
        if isinstance(c, dict) and c.get("component_id"):
            out[str(c["component_id"])] = c
    return out


def _score_record(pred_record: Dict[str, Any]) -> Dict[str, Any]:
    targets = pred_record.get("targets") or []
    preds = _pred_map(pred_record)
    graded = []
    for target in targets:
        cid = target["component_id"]
        pred = preds.get(cid, {})
        status = pred.get("status") or "missing"
        item = {
            "component_id": cid,
            "target": target,
            "prediction": pred,
            "status": status,
        }

        if target["kind"] == "delta":
            gt_sign = target["sign"]
            pred_sign = _canonical_direction(pred.get("direction"))
            recovered = status == "recovered" and pred_sign is not None
            sign_match = bool(recovered and pred_sign == gt_sign)
            mag = _to_float(pred.get("magnitude"))
            signed = _to_float(pred.get("signed_delta"))
            pred_signed = None
            if signed is not None:
                pred_signed = signed
                if pred_sign is None:
                    pred_sign = _sign(signed)
            elif mag is not None and pred_sign in ("+", "-", "0"):
                if pred_sign == "-":
                    pred_signed = -abs(mag)
                elif pred_sign == "+":
                    pred_signed = abs(mag)
                else:
                    pred_signed = 0.0
            abs_error = (
                abs(pred_signed - target["delta_value"])
                if pred_signed is not None else None
            )
            item.update({
                "delta_recovered": recovered,
                "gt_sign": gt_sign,
                "pred_sign": pred_sign,
                "sign_match": sign_match,
                "pred_signed_delta": pred_signed,
                "abs_error": abs_error,
            })

        elif target["kind"] == "scalar":
            val = _to_float(pred.get("scalar_value"))
            if val is None:
                val = _to_float(pred.get("magnitude"))
            recovered = status == "recovered" and val is not None
            err = abs(val - target["target_value"]) if val is not None else None
            tol = target.get("tolerance", 0.5)
            item.update({
                "scalar_recovered": recovered,
                "pred_value": val,
                "abs_error": err,
                "within_tolerance": bool(recovered and err is not None and err <= tol),
            })
        graded.append(item)

    return {
        "query_id": pred_record.get("query_id"),
        "type_k": pred_record.get("type_k"),
        "scenario": pred_record.get("scenario"),
        "status": pred_record.get("status"),
        "target_count": len(targets),
        "graded_components": graded,
        "record_summary": _summary_from_components(graded),
    }


def _summary_from_components(components: List[Dict[str, Any]]) -> Dict[str, Any]:
    delta = [c for c in components if c["target"]["kind"] == "delta"]
    scalar = [c for c in components if c["target"]["kind"] == "scalar"]
    delta_rec = [c for c in delta if c.get("delta_recovered")]
    sign_matches = [c for c in delta if c.get("sign_match")]
    mag = [c for c in delta_rec if c.get("abs_error") is not None]
    scal_rec = [c for c in scalar if c.get("scalar_recovered")]
    scal_ok = [c for c in scalar if c.get("within_tolerance")]
    scal_err = [c for c in scal_rec if c.get("abs_error") is not None]
    return {
        "delta_targets": len(delta),
        "delta_recovered": len(delta_rec),
        "sign_matches": len(sign_matches),
        "scalar_targets": len(scalar),
        "scalar_recovered": len(scal_rec),
        "scalar_within_tolerance": len(scal_ok),
        "magnitude_mae": (
            sum(c["abs_error"] for c in mag) / len(mag) if mag else None
        ),
        "scalar_mae": (
            sum(c["abs_error"] for c in scal_err) / len(scal_err) if scal_err else None
        ),
    }


def _aggregate(records: List[Dict[str, Any]]) -> Dict[str, Any]:
    groups = {
        "overall": records,
        "by_type_k": defaultdict(list),
        "by_scenario": defaultdict(list),
    }
    for r in records:
        groups["by_type_k"][str(r.get("type_k"))].append(r)
        groups["by_scenario"][str(r.get("scenario"))].append(r)

    def agg(rs: List[Dict[str, Any]]) -> Dict[str, Any]:
        comps = [c for r in rs for c in r.get("graded_components", [])]
        delta = [c for c in comps if c["target"]["kind"] == "delta"]
        scalar = [c for c in comps if c["target"]["kind"] == "scalar"]
        delta_rec = [c for c in delta if c.get("delta_recovered")]
        sign_matches = [c for c in delta if c.get("sign_match")]
        mag = [c for c in delta_rec if c.get("abs_error") is not None]
        scalar_rec = [c for c in scalar if c.get("scalar_recovered")]
        scalar_ok = [c for c in scalar if c.get("within_tolerance")]
        scalar_err = [c for c in scalar_rec if c.get("abs_error") is not None]
        gt_vals = [c["target"]["delta_value"] for c in mag]
        pred_vals = [c["pred_signed_delta"] for c in mag]
        return {
            "records": len(rs),
            "records_with_targets": sum(1 for r in rs if r.get("target_count", 0) > 0),
            "status_counts": dict(Counter(r.get("status") for r in rs)),
            "delta_targets": len(delta),
            "delta_recovered": len(delta_rec),
            "delta_coverage_rate": len(delta_rec) / len(delta) if delta else 0.0,
            "sign_matches": len(sign_matches),
            "sign_match_rate_all": len(sign_matches) / len(delta) if delta else 0.0,
            "sign_match_rate_recovered": (
                len(sign_matches) / len(delta_rec) if delta_rec else 0.0
            ),
            "magnitude_n": len(mag),
            "magnitude_mae": (
                sum(c["abs_error"] for c in mag) / len(mag) if mag else None
            ),
            "spearman_n": len(mag),
            "spearman": _spearman(gt_vals, pred_vals) if len(mag) >= 2 else None,
            "scalar_targets": len(scalar),
            "scalar_recovered": len(scalar_rec),
            "scalar_coverage_rate": (
                len(scalar_rec) / len(scalar) if scalar else 0.0
            ),
            "scalar_within_tolerance": len(scalar_ok),
            "scalar_within_tolerance_rate": (
                len(scalar_ok) / len(scalar) if scalar else 0.0
            ),
            "scalar_mae": (
                sum(c["abs_error"] for c in scalar_err) / len(scalar_err)
                if scalar_err else None
            ),
        }

    return {
        "overall": agg(groups["overall"]),
        "by_type_k": {k: agg(v) for k, v in sorted(groups["by_type_k"].items())},
        "by_scenario": {k: agg(v) for k, v in sorted(groups["by_scenario"].items())},
    }


def _load_type_map(query_csv: str) -> Dict[str, int]:
    out = {}
    if not os.path.exists(query_csv):
        return out
    with open(query_csv) as f:
        for row in csv.DictReader(f):
            out[row["query_id"]] = int(row["type_k"])
    return out


def grade_predictions(prediction_records: List[Dict[str, Any]],
                      args: argparse.Namespace) -> Dict[str, Any]:
    type_map = _load_type_map(args.query_csv)
    graded = []
    for rec in prediction_records:
        if rec.get("query_id") in type_map:
            rec["type_k"] = type_map[rec["query_id"]]
        graded.append(_score_record(rec))
    summary = _aggregate(graded)
    return {
        "method_name": args.method_name,
        "created_at": datetime.now(timezone.utc).isoformat().replace("+00:00", "Z"),
        "summary": summary,
        "records": graded,
    }


def _print_summary(summary: Dict[str, Any]) -> None:
    overall = summary["overall"]
    print("\n=== Delta-Recovery Overall ===")
    print(
        f"  delta sign-match(all): {overall['sign_matches']}/"
        f"{overall['delta_targets']} = {overall['sign_match_rate_all']*100:.1f}%"
    )
    print(
        f"  delta coverage       : {overall['delta_recovered']}/"
        f"{overall['delta_targets']} = {overall['delta_coverage_rate']*100:.1f}%"
    )
    print(
        f"  sign-match(recovered): {overall['sign_match_rate_recovered']*100:.1f}%"
    )
    print(f"  magnitude MAE        : {overall['magnitude_mae']}")
    print(f"  Spearman             : {overall['spearman']}")
    print(
        f"  scalar interval hit  : {overall['scalar_within_tolerance']}/"
        f"{overall['scalar_targets']} = "
        f"{overall['scalar_within_tolerance_rate']*100:.1f}%"
    )

    print("\n=== By type_k ===")
    for tk, d in summary["by_type_k"].items():
        if d["delta_targets"] == 0 and d["scalar_targets"] == 0:
            continue
        print(
            f"  type {tk:>2s}: sign_all={d['sign_match_rate_all']*100:5.1f}% "
            f"coverage={d['delta_coverage_rate']*100:5.1f}% "
            f"delta={d['sign_matches']}/{d['delta_targets']} "
            f"scalar_hit={d['scalar_within_tolerance']}/{d['scalar_targets']}"
        )


def parse_args() -> argparse.Namespace:
    p = argparse.ArgumentParser(description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--method-name", required=True,
                   help="Label for the method being evaluated, e.g. ours or b4")
    p.add_argument("--explanations", default=DEFAULT_EXPLANATIONS,
                   help="Method explanation/evidence JSON")
    p.add_argument("--reference-evidence", default=DEFAULT_REFERENCE,
                   help="Full evidence JSON used to build hidden delta targets")
    p.add_argument("--predictions-output", default=DEFAULT_PREDICTIONS,
                   help="LLM delta extraction output JSON")
    p.add_argument("--graded-output", default=DEFAULT_GRADED,
                   help="Scored Delta-Recovery output JSON")
    p.add_argument("--query-csv", default=DEFAULT_QUERY_CSV)
    p.add_argument("--query-ids", nargs="+")
    p.add_argument("--limit", type=int)
    p.add_argument("--model", default=DEFAULT_MODEL)
    p.add_argument("--workers", type=int, default=4)
    p.add_argument("--resume", action="store_true")
    p.add_argument("--skip-llm", action="store_true",
                   help="Build targets and write skipped predictions without API calls")
    p.add_argument("--timeout-sec", type=float, default=180.0)
    p.add_argument("--min-prob-delta-pp", type=float, default=1.0,
                   help="Minimum PCTL/probability change in percentage points")
    p.add_argument("--min-minute-delta", type=float, default=1.0)
    p.add_argument("--min-count-delta", type=float, default=0.5)
    p.add_argument("--min-raw-delta", type=float, default=0.05)
    p.add_argument("--max-delta-targets", type=int, default=12,
                   help="Max non-scalar delta targets per query; 0 disables cap")
    p.add_argument("--include-zero-deltas", action="store_true")
    return p.parse_args()


def _filter_records(records: List[Dict[str, Any]], args: argparse.Namespace
                    ) -> List[Dict[str, Any]]:
    out = records
    if args.query_ids:
        qids = set(args.query_ids)
        out = [r for r in out if r.get("query_id") in qids]
    if args.limit is not None:
        out = out[:args.limit]
    return out


def main() -> int:
    args = parse_args()
    _load_dotenv()
    if args.max_delta_targets is not None and args.max_delta_targets <= 0:
        args.max_delta_targets = None

    expl_records = _filter_records(_read_json(args.explanations), args)
    ref_records = _read_json(args.reference_evidence)
    ref_by_id = {r["query_id"]: r for r in ref_records}
    if not expl_records:
        print("No explanation records to evaluate.")
        return 0

    t0 = time.time()
    prediction_records = asyncio.run(_run_predictions(expl_records, ref_by_id, args))
    graded = grade_predictions(prediction_records, args)
    _write_json_atomic(args.graded_output, graded)
    _print_summary(graded["summary"])
    print(f"\nPredictions -> {args.predictions_output}")
    print(f"Graded      -> {args.graded_output}")
    print(f"Elapsed     -> {time.time() - t0:.1f}s")
    return 0


if __name__ == "__main__":
    sys.exit(main())
